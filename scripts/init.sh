# Unit tests source this script to exercise the functions above. The sentinel
# below stops before any side effects. See test/compare-versions.sh.t
if [ -n "${SOURCE_FUNCTIONS_ONLY}" ]; then
  return 0
fi

# Check for binaries

PKG_MANAGER="$(detect_pkg_manager)"

if [ -z "${PKG_MANAGER}" ]; then
  warn "WARNING: neither Homebrew nor MacPorts was found!"
  warn "Installing one of them is highly recommended."
fi

if ! [ -x "$(command -v git)" ]; then
  err 'Git is not installed. Use `brew install git` or `sudo port install git` to install.'
  exit 1
fi

# check minimum version for git config core.hooksPath
git_version=`git --version | perl -pe '($_)=/([0-9]+([.][0-9]+)+)/'`
if [ "$(compareVersions "$MIN_GIT_VERSION" "$git_version")" -eq 1 ] ; then
  err "Git version $git_version must be >= $MIN_GIT_VERSION. Use \`brew upgrade git\` or \`sudo port selfupdate && sudo port upgrade git\` to upgrade."
  exit 1
fi

if ! [ -x "$(command -v git-lfs)" ]; then
  err 'Git LFS is not installed. Use `brew install git-lfs` or `sudo port install git-lfs` to install.'
  exit 1
fi

# Refuse to run an init.sh older than the one that wrote this repo's hooks --
# it would regenerate the dispatchers from an older template and rewrite the
# marker downward, which is exactly the oscillating diff this design removes.
# Checked here, before .gitignore or .githooks is touched, so that a stale
# script changes nothing on its way out.
#
# init.sh is committed alongside .githooks in a Logic repo, so the script and
# the marker arrive in the same commit and this should never fire in normal
# use. It fires when someone drops a newer init.sh into the working tree and
# runs it before committing, or has local edits git pull cannot fast-forward.
marker_self="$(read_marker "${NEW_HOOKS_DIR}/${VERSIONS_FILE}" "${KEY_SELF}")"
if [ "$(compareVersions "${RELEASE_VERSION#v}" "${marker_self#v}")" -eq -1 ]; then
  err "This repo's hooks were written by git-logic-init ${marker_self}, but this init.sh is ${RELEASE_VERSION}."
  err 'Run `git pull` to pick up the newer init.sh, then run `bash init.sh` again.'
  err 'If init.sh is untracked or locally modified, Git cannot update it -- replace it from GitHub Releases.'
  exit 1
fi

if ! [ -d "${NEW_HOOKS_DIR}" ]; then
  mkdir "${NEW_HOOKS_DIR}"
fi

if ! [ -f "${NEW_HOOKS_DIR}/git-store-meta.pl" ]; then
  info "Git Store Meta not found, downloading..."
  curl -s -L -OO "${RELEASE_BASEURL}/${RELEASE_VERSION}/git-store-meta{.pl,.pl.sha256}"
  shasum -a256 -c git-store-meta.pl.sha256
  if [ $? -ne 0 ]; then
    err "Error"
    exit 1
  fi
  mv "git-store-meta.pl" "${NEW_HOOKS_DIR}/git-store-meta.pl"
  mv "git-store-meta.pl.sha256" "${NEW_HOOKS_DIR}"
fi

# make sure local hook is executable, if exists
if [ -f "${NEW_HOOKS_DIR}/git-store-meta.pl" ]; then
  chmod a+x "${NEW_HOOKS_DIR}/git-store-meta.pl"
fi

# Check ignore rules. Assume owner of repo has access to all plugins so
# that Freeze Files are not needed. Otherwise, manually zip up the Freeze Files
# folder if needed to the archive
touch .gitignore
for g in "${GIT_IGNORE[@]}"; do
  # Special thanks to:
  # https://stackoverflow.com/a/3557165/1603489
  grep -qxF "$g" .gitignore || echo "$g" >> .gitignore
done

if [ "$(git diff --name-only .gitignore | wc -l)" -gt 0 ]; then
  info "Changes successfully made to .gitignore"
  err "Please commit changes first and then re-run init.sh again"
  exit
fi

if ! [ -d "./.git" ]; then
  init_repo
fi

if ! [ -f ".gitattributes" ]; then
  init_lfs
elif ! grep -q "lfs" ".gitattributes"; then
  init_lfs
fi

# check if repo has a remote, pull LFS files
git rev-parse --abbrev-ref --symbolic-full-name @{u} >/dev/null 2>&1
if [ $? -eq 0 ]; then
  git lfs pull
fi

# An ignored marker would read as "0" on every fresh clone, so every clone would
# regenerate and commit the hooks again -- the exact churn this file prevents.
if git check-ignore -q "${NEW_HOOKS_DIR}/${VERSIONS_FILE}" 2>/dev/null; then
  warn "${NEW_HOOKS_DIR}/${VERSIONS_FILE} is matched by a .gitignore rule."
  warn "It has to be committed, or the hooks will be regenerated on every clone."
fi

# Which parts actually get regenerated is decided inside, per tool, against
# .githooks/VERSIONS -- so this is safe to run every time.
if ! bootstrap_hooks; then
  err "Error setting up commit hooks"
  exit 1
fi

# enable pre-commit hook
touch .git_store_meta

# initialize hooks location (must be done after each clone)
git config core.hooksPath "${NEW_HOOKS_DIR}"
info "git config core.hooksPath [${NEW_HOOKS_DIR}] successfully initialized"

# apply changes for fresh clones
if [ -s .git_store_meta ]
then
   ./"${NEW_HOOKS_DIR}/git-store-meta.pl" --apply
else
   # configure empty file
   ./"${NEW_HOOKS_DIR}/git-store-meta.pl" --store -f "${GIT_META_FIELDS}"
fi
if [ $? -ne 0 ]; then
  err "Error"
  exit 1
fi

info "Cheers!"
